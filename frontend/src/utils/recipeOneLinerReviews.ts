export const getRecipeOneLinerReviewText = (
  name: string,
  recipeId: number
): string => {
  const exact = RECIPE_ONE_LINER_REVIEWS[name];
  if (exact) return exact;

  for (const rule of KEYWORD_REVIEWS) {
    if (rule.keywords.some((keyword) => name.includes(keyword))) {
      return `「${name}」${rule.review}`;
    }
  }

  return PLAYFUL_FALLBACKS[recipeId % PLAYFUL_FALLBACKS.length](name);
};
